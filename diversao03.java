public class diversao03 {
    public static void main(String[] args) {
        // Escreva um programa que imprima os números impares de 1 a 51 e os pares de 52 a 100
        for(int i = 1; i <= 51; i += 2){
            System.out.println(i);
        }
        
        for(int i = 52; i <= 100; i += 2){
            System.out.println(i);
        }
    }
}